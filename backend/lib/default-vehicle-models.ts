/**
 * Canonical default catalog for inventory `Model` rows.
 * Upsert keys on `slug` so admins can customize names/brands safely.
 *
 * Curated global nameplates (not exhaustive worldwide trims/YMY).
 * Run `npx prisma db seed` after edits to sync into PostgreSQL.
 */

export type DefaultVehicleModelSeed = Readonly<{
  name: string;
  slug: string;
  brand: string;
  bodyType?: string | null;
}>;

type RawModel = readonly [string, string, string, string?];

function expand(rows: readonly RawModel[]): DefaultVehicleModelSeed[] {
  return rows.map(([brand, name, slug, bodyType]) => ({
    brand,
    name,
    slug,
    bodyType: bodyType ?? null,
  }));
}

